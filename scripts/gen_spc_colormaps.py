#!/usr/bin/env python3
"""Generates shared/src/commonMain/kotlin/simplemodelview/SpcColormaps.kt from the color tables of SPC's own REFS viewer.

fixtures/spc-site/primary-colormaps.json holds, per stored variable, the table of the viewer's main filled layer: levels, colors (RGBA floats),
the colors below / above them and the layer opacity. It was captured by running the viewer (https://www.spc.noaa.gov/exper/refs/viewer/, script
spc-refs-viewer.js) in a browser with its colormap (`qi`), layer (`Em`) and layer-set (`Pm`) constructors instrumented to record their arguments,
then taking, for each variable, the first non-overlay filled layer of the layer set that shows it. See docs/spc-colormaps.md.

Usage: gen_spc_colormaps.py > shared/src/commonMain/kotlin/simplemodelview/SpcColormaps.kt
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
tables = json.load(open(os.path.join(HERE, '..', 'fixtures', 'spc-site', 'primary-colormaps.json')))

def hexc(c):
    return '%02x%02x%02x' % tuple(round(x * 255) for x in c[:3])

def effective(levels, colors):
    """The bands the viewer's shader actually draws. For a table whose levels increase this is the table itself. The viewer maps a value to a color
    through a piecewise-linear lookup over `levels` (the first interval containing it) and then takes the nearest color, so a table with a typo
    (the helicity tables have ... 380, 520, 460, 500) is drawn by that rule: replicate it and merge equal neighbors into bands."""
    if all(a < b for a, b in zip(levels, levels[1:])):
        return levels, colors
    n = len(levels) - 1
    span = levels[-1] - levels[0]
    sx = [(v - levels[0]) / span for v in levels]
    def index(value):
        e = (value - levels[0]) / span
        t = 0
        while not (sx[t] <= e <= sx[t + 1]):
            t += 1
        frac = (e - sx[t]) / (sx[t + 1] - sx[t])
        pos = t / n * (1 - frac) + (t + 1) / n * frac
        return min(int(pos * len(colors)), len(colors) - 1)
    edges, cols = [levels[0]], [index(levels[0])]
    v = levels[0]
    while v < levels[-1]:
        v += 0.05
        i = index(min(v, levels[-1]))
        if i != cols[-1]:
            near = min(levels, key=lambda l: abs(l - v))
            edges.append(near if abs(near - v) < 0.1 else round(v, 2)); cols.append(i)   # (edges fall on the table's own levels)
    edges.append(levels[-1])
    return edges, [colors[i] for i in cols]

def num(v):
    return ('%g' % v) if abs(v) < 1e6 else repr(v)

print('''package simplemodelview

// GENERATED by scripts/gen_spc_colormaps.py from fixtures/spc-site/primary-colormaps.json: do not edit by hand.
// The color tables of SPC's REFS viewer, per stored variable: band edges ("levels"), one color per band, the colors below the first level /
// above the last (empty: transparent) and the layer opacity (0 = fully opaque).

/** One table of the viewer: [levels] has one more entry than [colors]; [under] / [over] are 0xRRGGBB or null. */
internal class SiteTable(val levels: DoubleArray, val colors: IntArray, val under: Int?, val over: Int?, val opacity: Double)

internal object SpcColormaps {
    private fun table(levels: String, colors: String, under: String = "", over: String = "", opacity: Double = 1.0) = SiteTable(
        levels.split(',').map { it.toDouble() }.toDoubleArray(), colors.split(',').map { it.toInt(16) }.toIntArray(),
        under.takeIf { it.isNotEmpty() }?.toInt(16), over.takeIf { it.isNotEmpty() }?.toInt(16), opacity,
    )

    val tables: Map<String, SiteTable> = mapOf(''')
for name in sorted(tables):
    t = tables[name]; cm = t['cmap']
    lv, cl = effective(cm['levels'], cm['colors'])
    levels = ','.join(num(x) for x in lv)
    colors = ','.join(hexc(c) for c in cl)
    under = hexc(cm['under']) if cm['under'] else ''
    over = hexc(cm['over']) if cm['over'] else ''
    op = t.get('opacity')
    extra = ''
    if under: extra += ', under = "%s"' % under
    if over: extra += ', over = "%s"' % over
    if op is not None and op < 1: extra += ', opacity = %s' % num(op)
    print('        "%s" to table("%s", "%s"%s),' % (name, levels, colors, extra))
print('    )\n}')
